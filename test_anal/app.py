@dataclass
class GigaChatConfig:
    auth_key: str
    scope: str
    model: str
    base_url: str
    oauth_url: str
    verify_ssl: bool
    timeout_sec: int
    temperature: float
    max_tokens: int


class GigaChatClient:
    def __init__(self, config: GigaChatConfig):
        self.config = config
        self._access_token: Optional[str] = None
        self._expires_at_ms: int = 0

    def _auth_header_value(self) -> str:
        value = self.config.auth_key.strip()

        if value.lower().startswith("basic "):
            return value

        return f"Basic {value}"

    def get_access_token(self) -> str:
        now_ms = int(time.time() * 1000)

        if self._access_token and now_ms < self._expires_at_ms - 60_000:
            return self._access_token

        headers = {
            "Content-Type": "application/x-www-form-urlencoded",
            "Accept": "application/json",
            "RqUID": str(uuid.uuid4()),
            "Authorization": self._auth_header_value(),
        }

        data = {
            "scope": self.config.scope,
        }

        response = requests.post(
            self.config.oauth_url,
            headers=headers,
            data=data,
            timeout=self.config.timeout_sec,
            verify=self.config.verify_ssl,
        )

        if response.status_code != 200:
            raise RuntimeError(
                f"GigaChat OAuth error {response.status_code}: {response.text}"
            )

        payload = response.json()

        token = payload.get("access_token")
        expires_at = payload.get("expires_at")

        if not token:
            raise RuntimeError(
                f"GigaChat OAuth response has no access_token: {payload}"
            )

        self._access_token = token

        if isinstance(expires_at, int):
            self._expires_at_ms = expires_at if expires_at > 10_000_000_000 else expires_at * 1000
        else:
            self._expires_at_ms = now_ms + 25 * 60 * 1000

        return self._access_token

    def chat_json(
        self,
        system_prompt: str,
        user_payload: Dict[str, Any],
        expected_root_key: str,
    ) -> Dict[str, Any]:
        messages = [
            {
                "role": "system",
                "content": system_prompt,
            },
            {
                "role": "user",
                "content": json.dumps(user_payload, ensure_ascii=False, indent=2),
            },
        ]

        raw_text = self._chat_text(messages)

        try:
            data = parse_json_from_model(raw_text)
            validate_root_key(data, expected_root_key)
            return data
        except Exception:
            repair_messages = [
                {
                    "role": "system",
                    "content": (
                        "Исправь ответ. Верни только валидный JSON без markdown и без пояснений. "
                        f"Обязательный корневой ключ: {expected_root_key}."
                    ),
                },
                {
                    "role": "user",
                    "content": raw_text,
                },
            ]

            repaired_text = self._chat_text(repair_messages)
            data = parse_json_from_model(repaired_text)
            validate_root_key(data, expected_root_key)
            return data

    def _chat_text(self, messages: List[Dict[str, str]]) -> str:
        token = self.get_access_token()

        url = f"{self.config.base_url.rstrip('/')}/chat/completions"

        headers = {
            "Content-Type": "application/json",
            "Accept": "application/json",
            "Authorization": f"Bearer {token}",
        }

        body = {
            "model": self.config.model,
            "messages": messages,
            "temperature": self.config.temperature,
            "max_tokens": self.config.max_tokens,
        }

        response = requests.post(
            url,
            headers=headers,
            json=body,
            timeout=self.config.timeout_sec,
            verify=self.config.verify_ssl,
        )

        if response.status_code != 200:
            raise RuntimeError(
                f"GigaChat chat error {response.status_code}: {response.text}"
            )

        payload = response.json()

        try:
            return payload["choices"][0]["message"]["content"]
        except Exception as exc:
            raise RuntimeError(
                f"Unexpected GigaChat response format: {payload}"
            ) from exc


