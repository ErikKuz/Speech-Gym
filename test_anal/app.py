# 7. JSON VALIDATION
# ============================================================

def parse_json_from_model(text: str) -> Dict[str, Any]:
    cleaned = text.strip()

    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)

    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        start = cleaned.find("{")

        if start == -1:
            raise ValueError(
                f"JSON object not found in model response: {text[:500]}"
            )

        decoder = json.JSONDecoder()

        try:
            data, _ = decoder.raw_decode(cleaned[start:])
            return data
        except json.JSONDecodeError:
            end = cleaned.rfind("}")

            if end == -1 or end <= start:
                raise ValueError(
                    f"JSON object not found in model response: {text[:500]}"
                )

            return json.loads(cleaned[start:end + 1])


def validate_root_key(data: Dict[str, Any], root_key: str) -> None:
    if root_key not in data:
        raise ValueError(
            f"Expected root key '{root_key}', got keys: {list(data.keys())}"
        )


def to_clean_list(value: Any, limit: int) -> List[str]:
    if not isinstance(value, list):
        return []

    return [
        str(item).strip()
        for item in value
        if str(item).strip()
    ][:limit]


def validate_passport(data: Dict[str, Any]) -> Dict[str, Any]:
    passport = data.get("passport_pitch")

    if not isinstance(passport, dict):
        raise ValueError("passport_pitch must be object")

    return {
        "passport_pitch": {
            "strengths": to_clean_list(passport.get("strengths"), 3),
            "blockers": to_clean_list(passport.get("blockers"), 3),
            "next_version_changes": to_clean_list(passport.get("next_version_changes"), 3),
        }
    }


def validate_next_pitch_draft(data: Dict[str, Any]) -> Dict[str, Any]:
    draft = data.get("next_pitch_draft")

    if isinstance(draft, str):
        draft = {
            "title": "Следующая версия pitch",
            "full_text": draft,
        }

    if not isinstance(draft, dict):
        raise ValueError("next_pitch_draft must be object")

    full_text = normalize_text(str(draft.get("full_text") or draft.get("text") or ""))

    if not full_text:
        raise ValueError("next_pitch_draft.full_text must be non-empty")

    return {
        "next_pitch_draft": {
            "title": str(draft.get("title", "Следующая версия pitch")).strip() or "Следующая версия pitch",
            "full_text": full_text,
        }
    }


def validate_next_pitch(data: Dict[str, Any]) -> Dict[str, Any]:
    next_pitch = data.get("next_pitch")

    if isinstance(next_pitch, str):
        next_pitch = {
            "title": "Следующая версия pitch",
            "full_text": next_pitch,
            "blocks": [
                {
                    "label": "Следующая версия pitch",
                    "text": next_pitch,
                }
            ],
        }

    if not isinstance(next_pitch, dict):
        raise ValueError("next_pitch must be object")

    blocks_raw = next_pitch.get("blocks")
    blocks: List[Dict[str, str]] = []

    if isinstance(blocks_raw, list):
        for item in blocks_raw:
            if not isinstance(item, dict):
                continue

            label = str(item.get("label", "")).strip()
            text = str(item.get("text", "")).strip()

            if label and text:
                blocks.append(
                    {
                        "label": label,
                        "text": text,
                    }
                )

    full_text = str(next_pitch.get("full_text", "")).strip()

    if not full_text and blocks:
        full_text = "\n\n".join(block["text"] for block in blocks)

    if not blocks and full_text:
        blocks = [
            {
                "label": "Следующая версия pitch",
                "text": full_text,
            }
        ]

    return {
        "next_pitch": {
            "title": str(next_pitch.get("title", "Следующая версия pitch")).strip() or "Следующая версия pitch",
            "blocks": blocks,
            "full_text": full_text,
        }
    }


def validate_recommendations(data: Dict[str, Any]) -> Dict[str, Any]:
    recommendations = data.get("recommendations")

    if isinstance(recommendations, str):
        recommendations = {
            "summary": [recommendations],
            "changes": [],
        }

    if isinstance(recommendations, list):
        recommendations = {
            "summary": recommendations,
            "changes": [],
        }

    if not isinstance(recommendations, dict):
        recommendations = {}

    summary = to_clean_list(recommendations.get("summary"), 7)

    changes_raw = recommendations.get("changes")
    changes: List[Dict[str, Any]] = []

    if isinstance(changes_raw, list):
        for item in changes_raw:
            if not isinstance(item, dict):
                continue

            effect = item.get("audience_effect")

            if not isinstance(effect, dict):
                effect = {}

            change = {
                "title": str(item.get("title", "")).strip(),
                "before": str(item.get("before", "")).strip(),
                "after": str(item.get("after", "")).strip(),
                "why_before_weaker": str(item.get("why_before_weaker", "")).strip(),
                "why_after_better": str(item.get("why_after_better", "")).strip(),
                "audience_effect": {
                    "understands_better": str(effect.get("understands_better", "")).strip(),
                    "feels_more": str(effect.get("feels_more", "")).strip(),
                },
            }

            if change["title"] and change["before"] and change["after"]:
                changes.append(change)

    return {
        "recommendations": {
            "summary": summary,
            "changes": changes[:7],
        }
    }


