def str_to_bool(value: str) -> bool:
    return value.strip().lower() in {"1", "true", "yes", "y", "on"}


def load_config() -> GigaChatConfig:
    load_dotenv()

    auth_key = os.getenv("GIGACHAT_AUTH_KEY", "").strip()

    if not auth_key:
        raise RuntimeError("Не задан GIGACHAT_AUTH_KEY")

    return GigaChatConfig(
        auth_key=auth_key,
        scope=os.getenv("GIGACHAT_SCOPE", "GIGACHAT_API_PERS").strip(),
        model=os.getenv("GIGACHAT_MODEL", "GigaChat-Max").strip(),
        base_url=os.getenv(
            "GIGACHAT_BASE_URL",
            "https://gigachat.devices.sberbank.ru/api/v1",
        ).strip(),
        oauth_url=os.getenv(
            "GIGACHAT_OAUTH_URL",
            "https://ngw.devices.sberbank.ru:9443/api/v2/oauth",
        ).strip(),
        verify_ssl=str_to_bool(os.getenv("GIGACHAT_VERIFY_SSL", "true")),
        timeout_sec=int(os.getenv("GIGACHAT_TIMEOUT_SEC", "180")),
        temperature=float(os.getenv("GIGACHAT_TEMPERATURE", "0.2")),
        max_tokens=int(os.getenv("GIGACHAT_MAX_TOKENS", "8000")),
    )


def get_workflow() -> SpeechGymWorkflow:
    config = load_config()
    client = GigaChatClient(config)
    return SpeechGymWorkflow(client)


